const FRAMES = [FRAME_0, FRAME_1];

export function PixelAnt({
  frame = 0,
  direction = 1,
  className,
}: PixelAntProps) {
  const grid = FRAMES[frame];
  const pixelSize = 1; // SVG 단위, 실제 크기는 className으로 제어

  return (
    <svg
      viewBox="0 0 16 16"
      className={className}
      style={{ transform: direction === 1 ? "scaleX(-1)" : undefined }}
    >
      {grid.map((row, y) =>
        row.map((cell, x) =>
          cell ? (
            <rect
              key={`${y}-${x}`}
              x={x * pixelSize}
              y={y * pixelSize}
              width={pixelSize}
              height={pixelSize}
              className="fill-foreground"
            />
          ) : null,
        ),
      )}
    </svg>
  );
}
